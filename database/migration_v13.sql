-- v13: employer feedback on finished work.
--
-- The platform already proves a student *did* the work: a lecturer
-- supervised it, a company signed it off, and a certificate records it. What
-- it could not say is how well. An employer reading a Praxfolio had the fact
-- of completion and nothing about the person.
--
-- This is the missing half, and it is worth something only because of where
-- it comes from. The company that commissioned the brief writes it, from the
-- account that approved the work, against an assignment that is finished.
-- None of that is true of a reference a graduate types in themselves, which
-- is why this is the one claim on the site that can honestly be called
-- verified.
--
-- Safe to run more than once. Nothing here drops or rewrites existing data.

CREATE TABLE IF NOT EXISTS employer_feedback (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- One per placement, enforced here rather than in the route: a company
    -- that submits the form twice must not leave two contradictory records
    -- of the same student on the same brief.
    assignment_id   INT NOT NULL UNIQUE
                    REFERENCES assignments(id) ON DELETE CASCADE,

    -- Who at the company wrote it. Nullable because the feedback outlives
    -- the account: staff leave, and the record stays true regardless.
    author_id       INT REFERENCES users(id) ON DELETE SET NULL,

    -- Four scores rather than one. A single star tells a reader nothing
    -- about *what* was good, and the competencies are the part an employer
    -- hiring for a role actually reads.
    communication   SMALLINT NOT NULL CHECK (communication   BETWEEN 1 AND 5),
    problem_solving SMALLINT NOT NULL CHECK (problem_solving BETWEEN 1 AND 5),
    quality         SMALLINT NOT NULL CHECK (quality         BETWEEN 1 AND 5),
    professionalism SMALLINT NOT NULL CHECK (professionalism BETWEEN 1 AND 5),

    -- Derived by the database, not by whoever happens to be rendering it.
    -- Three templates showing an average computed three ways is a bug that
    -- surfaces as "the Praxfolio says 4.3 and the certificate says 4.0".
    overall         NUMERIC(2,1) GENERATED ALWAYS AS (
                        (communication + problem_solving
                         + quality + professionalism) / 4.0
                    ) STORED,

    comment         TEXT,

    -- The student decides whether this appears on their public Praxfolio,
    -- and it starts hidden. Publishing somebody's criticism of a named
    -- person the moment it is written, without asking them, is not a
    -- default any platform should take on a student's behalf.
    is_public       BOOLEAN NOT NULL DEFAULT FALSE,

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- The Praxfolio reads these by student, through the assignment. Postgres
-- already indexes assignment_id for the UNIQUE constraint; this one covers
-- "show me everything public for this student" without a sequential scan
-- once there is real traffic.
CREATE INDEX IF NOT EXISTS idx_employer_feedback_public
    ON employer_feedback (assignment_id) WHERE is_public;
