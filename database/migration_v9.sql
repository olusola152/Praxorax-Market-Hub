-- Project presentations. A student defends their work to the company over a
-- video call, with the supervising lecturer in the room. This stores the
-- appointment, who agreed to it, who actually turned up, and what the company
-- decided afterwards. The call itself is a video room; everything that has to
-- survive the call is here.

CREATE TABLE IF NOT EXISTS presentations (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id   INT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,

    -- Whoever put the slot forward. A student asking for a date and a company
    -- setting one are the same row with a different proposer.
    proposed_by     INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title           VARCHAR(160) NOT NULL,
    agenda          TEXT,

    -- The slot. starts_at is what was proposed; it is overwritten when a
    -- counter-proposal is accepted, so it always reads as the live time.
    starts_at       TIMESTAMPTZ NOT NULL,
    duration_mins   INT NOT NULL DEFAULT 30
                    CHECK (duration_mins BETWEEN 10 AND 240),

    -- 'jitsi' hosts the call inside PraxoraX and needs no account from
    -- anyone. 'external' is a Zoom or Meet link someone pasted — used when a
    -- company insists on its own platform.
    provider        VARCHAR(20) NOT NULL DEFAULT 'jitsi'
                    CHECK (provider IN ('jitsi','external')),
    room_name       VARCHAR(120),       -- jitsi: the room, unguessable
    external_url    VARCHAR(500),       -- external: the pasted link

    status          VARCHAR(20) NOT NULL DEFAULT 'proposed'
                    CHECK (status IN ('proposed','confirmed','live','held',
                                      'missed','cancelled')),

    -- Filled in once the call has happened.
    outcome         VARCHAR(20)
                    CHECK (outcome IS NULL OR outcome IN ('passed','rework','undecided')),
    outcome_notes   TEXT,
    outcome_by      INT REFERENCES users(id) ON DELETE SET NULL,
    outcome_at      TIMESTAMPTZ,

    -- Why a slot was turned down, so the next proposal can avoid the clash.
    decline_reason  TEXT,

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at      TIMESTAMPTZ,        -- first person through the door
    ended_at        TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_presentations_assignment
    ON presentations (assignment_id);
CREATE INDEX IF NOT EXISTS idx_presentations_upcoming
    ON presentations (starts_at) WHERE status IN ('proposed','confirmed','live');

-- One row per invited person, so a dashboard can ask "is this mine?" without
-- re-deriving the chain, and so attendance is a fact rather than a guess.
CREATE TABLE IF NOT EXISTS presentation_attendees (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presentation_id INT NOT NULL REFERENCES presentations(id) ON DELETE CASCADE,
    user_id         INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- 'presenter' is the student. 'host' may record the outcome and may
    -- confirm a slot. 'observer' is anyone else invited to watch.
    part            VARCHAR(20) NOT NULL DEFAULT 'observer'
                    CHECK (part IN ('presenter','host','observer')),

    response        VARCHAR(20) NOT NULL DEFAULT 'pending'
                    CHECK (response IN ('pending','accepted','declined')),
    responded_at    TIMESTAMPTZ,

    -- Attendance. Written the first time they open the room.
    joined_at       TIMESTAMPTZ,
    last_seen_at    TIMESTAMPTZ,

    UNIQUE (presentation_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_presentation_attendees_user
    ON presentation_attendees (user_id);
