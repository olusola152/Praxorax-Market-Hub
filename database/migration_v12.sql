-- v12  Contacts, feedback and supervision messages
--
-- Three things the client asked for, in one migration because they share a
-- single idea: the platform had no way for anybody to reach anybody else,
-- and no way for anybody to tell it what was wrong with it.
--
--   1. Social links, both PraxoraX's own and each person's.
--   2. A feedback survey — a star rating, what is missing, a suggestion.
--   3. A private thread between a student and their supervising lecturer.
--
-- Additive only. Nothing here drops or rewrites an existing column, so it is
-- safe to run against a database with real rows in it, and safe to run twice.

-- --------------------------------------------------------------- 1. links
--
-- One row per person per network rather than eight columns on users. The list
-- of networks that matter changes every couple of years and a table absorbs
-- that; eight columns means a migration every time somebody new turns up.
--
-- The platform's own accounts live in the same table with user_id NULL, so
-- one query and one template partial render either kind.

CREATE TABLE IF NOT EXISTS social_links (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER REFERENCES users(id) ON DELETE CASCADE,
    network     VARCHAR(20)  NOT NULL,
    handle      VARCHAR(200) NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- A person has at most one account per network; so does the platform. The
-- two partial indexes together say that, because NULL never equals NULL and
-- a single unique constraint would let the platform hold duplicates.
CREATE UNIQUE INDEX IF NOT EXISTS idx_social_person
    ON social_links (user_id, network) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_social_platform
    ON social_links (network) WHERE user_id IS NULL;

-- Whether a person's handles are shown to others at all. Default FALSE:
-- somebody who fills in their WhatsApp has not thereby agreed to publish it.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS links_public BOOLEAN NOT NULL DEFAULT FALSE;


-- ------------------------------------------------------------ 2. feedback
--
-- What people think of the platform: a rating out of five, what is missing,
-- and a free suggestion. Kept with who sent it where they were signed in,
-- and without when they were not, because a visitor should be able to say
-- something is broken without making an account first.

CREATE TABLE IF NOT EXISTS feedback (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER REFERENCES users(id) ON DELETE SET NULL,
    -- Kept even when user_id is set, because the account's address may
    -- change later and a reply should go where the person asked.
    reply_to    VARCHAR(150),
    rating      SMALLINT     NOT NULL CHECK (rating BETWEEN 1 AND 5),
    missing     TEXT,
    suggestion  TEXT,
    -- Where they were when they wrote it. A complaint makes much more sense
    -- next to the page it was about.
    page        VARCHAR(300),
    status      VARCHAR(20)  NOT NULL DEFAULT 'new'
                CHECK (status IN ('new', 'read', 'actioned', 'declined')),
    handled_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
    handled_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_feedback_new
    ON feedback (status, created_at DESC);


-- ------------------------------------------------------------ 3. messages
--
-- A student and their supervising lecturer, talking about a placement.
--
-- Scoped to an assignment rather than being a general inbox. The pair only
-- have a reason to talk because of a specific piece of work, and tying the
-- thread to it means the lecturer's list is "my placements", which they
-- already have, instead of a second thing to keep up with.

CREATE TABLE IF NOT EXISTS messages (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id INTEGER NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    sender_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body          TEXT    NOT NULL,
    sent_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_at       TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_messages_thread
    ON messages (assignment_id, sent_at);
-- Powers the unread count in the top bar, which runs on every page load.
CREATE INDEX IF NOT EXISTS idx_messages_unread
    ON messages (assignment_id, read_at) WHERE read_at IS NULL;
