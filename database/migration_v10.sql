-- A team invitation sent to an address rather than to an account.
--
-- team_members already handles invitations to people who are here; this
-- covers the gap before that, when the person has no row in users to point
-- at. On signup the invitation is converted into a team_members row and
-- marked accepted, so there is exactly one place that holds membership.
CREATE TABLE IF NOT EXISTS team_invitations (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id     INT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    email       VARCHAR(255) NOT NULL,
    invited_by  INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- Unguessable, and the only thing in the emailed link. It identifies the
    -- invitation without naming the team or the address to anyone who sees
    -- the URL over someone's shoulder.
    token       VARCHAR(64) NOT NULL UNIQUE,

    status      VARCHAR(20) NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending','accepted','cancelled','expired')),

    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at  TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    accepted_by INT REFERENCES users(id) ON DELETE SET NULL,

    -- One live invitation per address per team. A second invite to the same
    -- person updates the first rather than filling their inbox.
    UNIQUE (team_id, email)
);

CREATE INDEX IF NOT EXISTS idx_team_invitations_email
    ON team_invitations (email) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_team_invitations_token
    ON team_invitations (token);

-- When this student's profile first had everything a company needs to judge
-- them. NULL means it still does not. Kept as a timestamp rather than a flag
-- so "finished their profile but never applied" is answerable.
ALTER TABLE student_profiles
    ADD COLUMN IF NOT EXISTS completed_at TIMESTAMPTZ;
